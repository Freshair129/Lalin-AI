interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, variables?: Variables) => string;
  tPlural: (key: PluralTranslationKey, count: number) => string;
}

const fallback: I18nValue = {
  locale: "en",
  setLocale: () => undefined,
  t: (key, variables) => translate("en", key, variables),
  tPlural: (key, count) => translatePlural("en", key, count),
};
const I18nContext = createContext<I18nValue>(fallback);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(readLocale);
  const setLocale = (next: Locale) => {
    setLocaleState(next);
    try {
      localStorage.setItem(STORAGE_LOCALE_KEY, next);
    } catch {
      // Locale remains active for this session when storage is unavailable.
    }
  };
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t: (key, variables) => translate(locale, key, variables),
    tPlural: (key, count) => translatePlural(locale, key, count),
  }), [locale]);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
