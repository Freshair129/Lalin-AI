export type TranslationKey = keyof typeof en;
export type PluralTranslationKey = "recovery.notice" | "recovery.compactHint";
type Variables = Record<string, string | number>;

function readLocale(): Locale {
  try {
    return typeof localStorage !== "undefined" && localStorage.getItem(STORAGE_LOCALE_KEY) === "th" ? "th" : "en";
  } catch {
    return "en";
  }
}

function translate(locale: Locale, key: TranslationKey, variables?: Variables): string {
  let value = (locale === "th" ? th : en)[key] ?? en[key];
  if (variables) {
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

function translatePlural(locale: Locale, key: PluralTranslationKey, count: number): string {
  const form = new Intl.PluralRules(locale).select(count) === "one" ? "one" : "other";
  return translate(locale, `${key}.${form}` as TranslationKey, { count });
}

